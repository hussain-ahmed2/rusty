/// Sets the base path once, before any page is rendered.
pub(crate) fn set_base(raw: &str) {
    let _ = BASE.set(normalize_base(raw));
}

/// Returns the document base path, always with leading and trailing slashes.
pub(crate) fn base_path() -> &'static str {
    BASE.get().map_or("/", String::as_str)
}

/// Normalizes a GitHub Pages base path such as `/rusty` to `/rusty/`.
pub(crate) fn normalize_base(raw: &str) -> String {
    let trimmed = raw.trim().trim_matches('/');
    if trimmed.is_empty() {
        "/".to_owned()
    } else {
        format!("/{trimmed}/")
    }
}

/// Returns the home URL without a trailing slash for project pages.
pub(crate) fn home_url() -> String {
    let base = base_path().trim_end_matches('/');
    if base.is_empty() {
        "/".to_owned()
    } else {
        base.to_owned()
    }
}

/// Resolves a site path against the configured base path without a trailing slash.
pub(crate) fn url(path: &str) -> String {
    format!("{}{}", base_path(), path.trim_matches('/'))
}

/// Renders inline code delimited by backticks and escapes the surrounding text.
pub(crate) fn rich(text: &str) -> Element {
    let mut parts = Vec::new();
    for (index, part) in text.split('`').enumerate() {
        if part.is_empty() {
            continue;
        }
        if index % 2 == 1 {
            let part = part.to_owned();
            parts.push(view! { <code>{part}</code> });
        } else {
            parts.push(Element::text(part));
        }
    }
    Element::fragment(parts)
}

/// Finds a documentation page by slug.
pub(crate) fn doc(slug: &str) -> Option<&'static Doc> {
    DOCS.iter().find(|doc| doc.slug == slug)
}

/// Returns every path the static site generator should render.
pub(crate) fn paths() -> Vec<String> {
    let mut paths = vec!["/".to_owned(), "/about".to_owned(), "/docs".to_owned()];
    paths.extend(DOCS.iter().map(|doc| format!("/docs/{}", doc.slug)));
    paths
}

#[cfg(test)]
mod tests {
    use super::normalize_base;

    #[test]
    fn normalizes_project_page_base_paths() {
        assert_eq!(normalize_base(""), "/");
        assert_eq!(normalize_base("/"), "/");
        assert_eq!(normalize_base("rusty"), "/rusty/");
        assert_eq!(normalize_base("/rusty"), "/rusty/");
        assert_eq!(normalize_base("/rusty/"), "/rusty/");
    }
}
