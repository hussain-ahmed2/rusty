//! Typed server functions for Rusty.
//!
//! A server function is a normal Rust function annotated with
//! `#[rusty::server]`. The macro generates a marker type on every target and a
//! client stub on WebAssembly. Native servers register the marker in an
//! [`RpcRegistry`], which deserializes JSON arguments, calls the function, and
//! serializes the result.
//!
//! The client uses a [`Transport`] installed for the current thread:
//!
//! ```
//! use std::sync::Arc;
//! use rusty_rpc::{set_transport, Transport, RpcError};
//!
//! struct Echo;
//! impl Transport for Echo {
//!     fn call(&self, _path: &str, body: &[u8]) -> Result<Vec<u8>, RpcError> {
//!         Ok(body.to_vec())
//!     }
//! }
//!
//! let _guard = set_transport(Arc::new(Echo));
//! ```

#![forbid(unsafe_code)]
#![deny(missing_docs)]

use std::cell::RefCell;
use std::error::Error;
use std::fmt;
use std::sync::Arc;

use serde::de::DeserializeOwned;
use serde::Serialize;

#[cfg(not(target_arch = "wasm32"))]
use std::collections::BTreeMap;

#[cfg(not(target_arch = "wasm32"))]
use rusty_server::{Request, Response, ServerError, StatusCode};

/// An error from a server function call, registry, or transport.
#[derive(Debug, Clone, PartialEq, Eq)]
#[non_exhaustive]
pub enum RpcError {
    /// No transport is installed or the transport failed.
    Transport(String),
    /// Arguments or a result could not be serialized.
    Serialize(String),
    /// Arguments or a result could not be deserialized.
    Deserialize(String),
    /// A remote server returned an error status.
    Remote {
        /// The HTTP-style status code.
        status: u16,
        /// The remote error message.
        message: String,
    },
    /// No server function is registered at the requested path.
    UnknownFunction(String),
    /// The server function failed.
    Server(String),
}

impl RpcError {
    /// Returns the HTTP-style status code recommended for this error.
    #[must_use]
    pub fn status_code(&self) -> u16 {
        match self {
            Self::Serialize(_) | Self::Deserialize(_) => 400,
            Self::UnknownFunction(_) => 404,
            Self::Remote { status, .. } => *status,
            Self::Transport(_) | Self::Server(_) => 500,
        }
    }
}

impl fmt::Display for RpcError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Transport(message) => write!(formatter, "RPC transport failed: {message}"),
            Self::Serialize(message) => write!(formatter, "RPC serialization failed: {message}"),
            Self::Deserialize(message) => {
                write!(formatter, "RPC deserialization failed: {message}")
            }
            Self::Remote { status, message } => {
                write!(formatter, "RPC server returned {status}: {message}")
            }
            Self::UnknownFunction(path) => write!(formatter, "unknown RPC function at `{path}`"),
            Self::Server(message) => write!(formatter, "RPC server function failed: {message}"),
        }
    }
}

impl Error for RpcError {}

/// A typed server function that can be called from a client.
pub trait ServerFunction {
    /// The default HTTP path used to call the function.
    const PATH: &'static str;
    /// The JSON-serializable argument tuple.
    type Args: Serialize + DeserializeOwned;
    /// The JSON-serializable successful result.
    type Output: Serialize + DeserializeOwned;
}

/// A server-side function that can deserialize arguments and serialize results.
///
/// This trait is generated by `#[rusty::server]` and implemented only on
/// non-WebAssembly targets.
#[cfg(not(target_arch = "wasm32"))]
pub trait ServerInvoker: ServerFunction {
    /// Invokes the function with JSON arguments and returns JSON output.
    ///
    /// # Errors
    ///
    /// Returns [`RpcError`] when arguments cannot be decoded, the function
    /// fails, or the result cannot be encoded.
    fn invoke(&self, args: &[u8]) -> Result<Vec<u8>, RpcError>;
}

/// Implementation details used by `#[rusty::server]` expansions.
#[doc(hidden)]
pub mod __private {
    pub use serde_json::{from_slice, to_vec};
}

/// A transport that forwards JSON bodies to a server function path.
pub trait Transport: Send + Sync {
    /// Calls a server function and returns its JSON response body.
    ///
    /// # Errors
    ///
    /// Returns [`RpcError`] when the request fails.
    fn call(&self, path: &str, body: &[u8]) -> Result<Vec<u8>, RpcError>;
}

thread_local! {
    static TRANSPORT: RefCell<Option<Arc<dyn Transport>>> = const { RefCell::new(None) };
}

/// Restores the previous thread transport when dropped.
#[must_use = "dropping the guard immediately restores the previous transport"]
pub struct TransportGuard {
    previous: Option<Arc<dyn Transport>>,
}

impl Drop for TransportGuard {
    fn drop(&mut self) {
        let previous = self.previous.take();
        TRANSPORT.with(|slot| {
            slot.replace(previous);
        });
    }
}

/// Installs a transport for the current thread and returns a guard.
///
/// The previous transport is restored when the guard is dropped.
pub fn set_transport(transport: Arc<dyn Transport>) -> TransportGuard {
    let previous = TRANSPORT.with(|slot| slot.replace(Some(transport)));
    TransportGuard { previous }
}

/// Runs a closure with a transport installed for the current thread.
pub fn with_transport<T>(transport: Arc<dyn Transport>, call: impl FnOnce() -> T) -> T {
    let _guard = set_transport(transport);
    call()
}

/// Calls a server function through the current thread's transport.
///
/// # Errors
///
/// Returns [`RpcError::Transport`] when no transport is installed, or an error
/// from the transport.
pub fn call(path: &str, body: &[u8]) -> Result<Vec<u8>, RpcError> {
    let transport = TRANSPORT
        .with(|slot| slot.borrow().clone())
        .ok_or_else(|| RpcError::Transport("no RPC transport installed".to_owned()))?;
    transport.call(path, body)
}

/// Invokes a typed server function through a specific transport.
///
/// # Errors
///
/// Returns [`RpcError`] when serialization, transport, or deserialization fails.
pub fn invoke_with<F: ServerFunction>(
    transport: &dyn Transport,
    args: &F::Args,
) -> Result<F::Output, RpcError> {
    let body = serde_json::to_vec(args).map_err(|error| RpcError::Serialize(error.to_string()))?;
    let output = transport.call(F::PATH, &body)?;
    serde_json::from_slice(&output).map_err(|error| RpcError::Deserialize(error.to_string()))
}

/// Invokes a typed server function through the current thread's transport.
///
/// # Errors
///
/// Returns [`RpcError`] when no transport is installed, or when serialization,
/// transport, or deserialization fails.
pub fn invoke<F: ServerFunction>(args: &F::Args) -> Result<F::Output, RpcError> {
    let body = serde_json::to_vec(args).map_err(|error| RpcError::Serialize(error.to_string()))?;
    let output = call(F::PATH, &body)?;
    serde_json::from_slice(&output).map_err(|error| RpcError::Deserialize(error.to_string()))
}

/// A typed client bound to a specific transport.
#[derive(Clone)]
pub struct RpcClient {
    transport: Arc<dyn Transport>,
}

impl RpcClient {
    /// Creates a client using the given transport.
    #[must_use]
    pub fn new(transport: Arc<dyn Transport>) -> Self {
        Self { transport }
    }

    /// Invokes a typed server function.
    ///
    /// # Errors
    ///
    /// Returns [`RpcError`] when serialization, transport, or deserialization
    /// fails.
    pub fn invoke<F: ServerFunction>(&self, args: &F::Args) -> Result<F::Output, RpcError> {
        invoke_with::<F>(self.transport.as_ref(), args)
    }
}

#[cfg(not(target_arch = "wasm32"))]
type RpcHandler = Arc<dyn Fn(&[u8]) -> Result<Vec<u8>, RpcError> + Send + Sync>;

/// A registry of server functions callable over JSON.
#[cfg(not(target_arch = "wasm32"))]
#[derive(Clone, Default)]
pub struct RpcRegistry {
    functions: BTreeMap<&'static str, RpcHandler>,
}

#[cfg(not(target_arch = "wasm32"))]
impl RpcRegistry {
    /// Creates an empty registry.
    #[must_use]
    pub fn new() -> Self {
        Self::default()
    }

    /// Registers a server function marker.
    ///
    /// # Errors
    ///
    /// Returns [`RpcError::Server`] when the path is already registered.
    pub fn register<F>(&mut self) -> Result<(), RpcError>
    where
        F: ServerInvoker + Default + Send + Sync + 'static,
    {
        if self.functions.contains_key(F::PATH) {
            return Err(RpcError::Server(format!(
                "RPC path `{}` is already registered",
                F::PATH
            )));
        }
        let function = F::default();
        self.functions
            .insert(F::PATH, Arc::new(move |args: &[u8]| function.invoke(args)));
        Ok(())
    }

    /// Returns the number of registered functions.
    #[must_use]
    pub fn len(&self) -> usize {
        self.functions.len()
    }

    /// Returns `true` when no functions are registered.
    #[must_use]
    pub fn is_empty(&self) -> bool {
        self.functions.is_empty()
    }

    /// Returns the registered function paths in sorted order.
    pub fn paths(&self) -> impl Iterator<Item = &'static str> + '_ {
        self.functions.keys().copied()
    }

    /// Invokes a registered function with JSON arguments.
    ///
    /// # Errors
    ///
    /// Returns [`RpcError::UnknownFunction`] for an unknown path or an error
    /// from the server function.
    pub fn invoke(&self, path: &str, args: &[u8]) -> Result<Vec<u8>, RpcError> {
        let function = self
            .functions
            .get(path)
            .ok_or_else(|| RpcError::UnknownFunction(path.to_owned()))?;
        function(args)
    }

    /// Handles an HTTP request carrying a JSON argument body.
    ///
    /// # Errors
    ///
    /// Returns [`ServerError`] when a response header cannot be constructed.
    pub fn handle(&self, request: &Request) -> Result<Response, ServerError> {
        if request.method() != rusty_server::Method::Post {
            return Ok(Response::text(
                StatusCode::METHOD_NOT_ALLOWED,
                "RPC endpoints require POST",
            ));
        }

        match self.invoke(request.path(), request.body()) {
            Ok(output) => Ok(Response::new(StatusCode::OK)
                .with_header("content-type", "application/json; charset=utf-8")?
                .with_body(output)),
            Err(error) => {
                let status = StatusCode::new(error.status_code())
                    .unwrap_or(StatusCode::INTERNAL_SERVER_ERROR);
                let body = serde_json::json!({ "error": error.to_string() }).to_string();
                Ok(Response::json(status, body))
            }
        }
    }
}
